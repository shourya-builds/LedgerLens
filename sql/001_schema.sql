CREATE SCHEMA IF NOT EXISTS LEDGERLENS;

CREATE TABLE IF NOT EXISTS LEDGERLENS.RAW_TRANSACTIONS (
    INGESTION_BATCH_ID VARCHAR(64),
    SOURCE_SYSTEM VARCHAR(64),
    SOURCE_ROW_ID VARCHAR(128),
    PAYLOAD VARCHAR(2000000),
    INGESTED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS LEDGERLENS.NORMALIZED_TRANSACTIONS (
    TRANSACTION_ID VARCHAR(256),
    SOURCE_SYSTEM VARCHAR(64),
    REFERENCE_ID VARCHAR(256),
    TRANSACTION_DATE DATE,
    SETTLEMENT_DATE DATE,
    AMOUNT DECIMAL(18, 2),
    CURRENCY VARCHAR(3),
    COUNTERPARTY VARCHAR(256),
    DESCRIPTION VARCHAR(2000),
    INGESTION_BATCH_ID VARCHAR(64),
    SOURCE_ROW_ID VARCHAR(128)
);

CREATE TABLE IF NOT EXISTS LEDGERLENS.RECONCILIATION_RESULTS (
    LEFT_TRANSACTION_ID VARCHAR(256),
    RIGHT_TRANSACTION_ID VARCHAR(256),
    STATUS VARCHAR(64),
    MATCHING_RULE VARCHAR(128),
    AMOUNT_DIFFERENCE DECIMAL(18, 2),
    DATE_DIFFERENCE_DAYS INTEGER,
    AMOUNT_AT_RISK DECIMAL(18, 2),
    EXPLANATION VARCHAR(2000),
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS LEDGERLENS.INVESTIGATION_QUEUE (
    LEFT_TRANSACTION_ID VARCHAR(256),
    RIGHT_TRANSACTION_ID VARCHAR(256),
    PRIORITY VARCHAR(16),
    PRIORITY_SCORE DECIMAL(18, 2),
    ROOT_CAUSE VARCHAR(128),
    RECOMMENDED_ACTION VARCHAR(2000),
    STATUS VARCHAR(32) DEFAULT 'OPEN'
);

